#!/usr/bin/env python3
"""compress-context.py — compact repo/context map for small-context models.

Part of the cross-agent framework's local-model tooling, and the companion to
split-task.py. Produces a COMPACT markdown map of a codebase — a file inventory
plus extracted top-level symbols (Python `def`/`class`, Markdown headings) — so a
small-context model gets a useful map of the repo WITHOUT a full repo dump.

The DEFAULT map is a DETERMINISTIC extractor, not an intelligent ranker: it lists
what exists and the top-level signatures (Python `def`/`class`, Markdown
headings), compactly.

`--smart` (Epic E1, opt-in) adds, still deterministically and still fail-closed
on the budgets: JS/TS symbol extraction, an intra-repo import graph, a file
ranking by in-degree centrality, and entrypoint detection. There is no LLM in the
mapper; the same tree yields a byte-identical smart map. The default (no --smart)
output is unchanged.

Usage:
    scripts/compress-context.py [root] [--smart] [--out <file>] [--max-symbols N]
                                [--exclude name,name] [--selftest]

Defaults: root = current directory; output = stdout. Common noise directories
(.git, __pycache__, node_modules, .venv, ...) are excluded; add more with
--exclude.
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import re
import sys
import tempfile
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS_DIR))

# Shared with wf-map.py — see scripts/_langmap.py for what is deliberately NOT
# shared (this tool's own exclusion additions and its h1-h2 heading depth).
from _langmap import (  # noqa: E402
    BASE_EXCLUDES, JS_EXTS, JS_IMPORT_RES, JS_SYMBOL_RULES, PY_EXTS,
    PY_SYMBOL_RE, SIG_MAXLEN, md_heading_re,
)

DEFAULT_EXCLUDES = set(BASE_EXCLUDES) | {".DS_Store"}
MD_HEADING_RE = md_heading_re(2)

# --- smart mode (Epic E1) -----------------------------------------------------
SOURCE_EXTS = PY_EXTS + JS_EXTS
PY_FROM_RE = re.compile(r"^\s*from\s+(\.*[\w.]*)\s+import\s+(.+)$")
PY_IMPORT_RE = re.compile(r"^\s*import\s+([\w.]+(?:\s*,\s*[\w.]+)*)")
ENTRY_STEMS = {"main", "index", "app", "cli", "__main__", "server"}


def _human_size(n: int) -> str:
    size = float(n)
    for unit in ("B", "K", "M", "G"):
        if size < 1024 or unit == "G":
            return f"{int(size)}{unit}" if unit == "B" else f"{size:.0f}{unit}"
        size /= 1024
    return f"{int(n)}B"


def collect_files(root: Path, excludes: set[str]) -> list[Path]:
    files: list[Path] = []
    for p in sorted(root.rglob("*")):
        if any(part in excludes for part in p.relative_to(root).parts):
            continue
        if p.is_file():
            files.append(p)
    return files


def extract_symbols(path: Path, max_symbols: int, include_js: bool = False) -> list[str]:
    try:
        text = path.read_text(errors="ignore")
    except OSError:
        return []
    syms: list[str] = []
    if path.suffix == ".py":
        for line in text.splitlines():
            if line and not line[0].isspace() and PY_SYMBOL_RE.match(line):
                sig = line.rstrip()
                if sig.endswith(":"):
                    sig = sig[:-1].rstrip()
                syms.append(sig.strip()[:SIG_MAXLEN])
    elif path.suffix in (".md", ".markdown"):
        for line in text.splitlines():
            m = MD_HEADING_RE.match(line)
            if m:
                syms.append(f"{m.group(1)} {m.group(2)}"[:SIG_MAXLEN])
    elif include_js and path.suffix in JS_EXTS:
        # JS/TS symbols are SMART-ONLY — never extracted in the default map, so
        # the default output stays byte-identical for repos containing JS/TS.
        for line in text.splitlines():
            if line and not line[0].isspace() and \
                    any(r.match(line) for _, r in JS_SYMBOL_RULES):
                sig = line.rstrip()
                if sig.endswith("{"):
                    sig = sig[:-1].rstrip()
                syms.append(sig.strip()[:SIG_MAXLEN])
    return syms[:max_symbols]


def build_map(files: list[Path], root: Path, max_symbols: int) -> str:
    out = [
        "# Context map — " + (root.name or str(root)),
        "<!-- generated by scripts/compress-context.py -->",
        "",
        "Compact map for small-context models: file inventory + top-level symbols. "
        "Not a full repo dump.",
        "",
        f"## Files ({len(files)})",
    ]
    for f in files:
        rel = f.relative_to(root).as_posix()
        try:
            size = f.stat().st_size
        except OSError:
            size = 0
        out.append(f"- `{rel}` ({_human_size(size)})")

    out += ["", "## Symbols"]
    any_syms = False
    for f in files:
        syms = extract_symbols(f, max_symbols)
        if not syms:
            continue
        any_syms = True
        out.append(f"### `{f.relative_to(root).as_posix()}`")
        for s in syms:
            out.append(f"- {s}")
    if not any_syms:
        out.append("(no extractable symbols in supported languages)")
    return "\n".join(out).rstrip("\n") + "\n"


# --- smart mode: import graph + ranking (Epic E1) -----------------------------

def _file_imports(path: Path, text: str) -> list[tuple[str, str]]:
    """Return (kind, spec) import specifiers found in a source file."""
    specs: list[tuple[str, str]] = []
    if path.suffix in PY_EXTS:
        for line in text.splitlines():
            m = PY_FROM_RE.match(line)
            if m:
                mod, names = m.group(1), m.group(2)
                if mod.strip(".") == "":  # `from . import x, y` — names are modules
                    for nm in names.split(","):
                        nm = nm.strip().split(" as ")[0].strip().strip("()").strip()
                        if nm and nm != "*":
                            specs.append(("py", mod + nm))
                else:
                    specs.append(("py", mod))
                continue
            m = PY_IMPORT_RE.match(line)
            if m:
                for part in m.group(1).split(","):
                    tok = part.strip().split(" as ")[0].strip()
                    if tok:
                        specs.append(("py", tok))
    elif path.suffix in JS_EXTS:
        for raw in text.splitlines():
            s = raw.strip()
            if s.startswith(("//", "*", "/*")):  # skip comment lines
                continue
            line = raw.split("//", 1)[0]  # drop a trailing line comment
            for r in JS_IMPORT_RES:
                specs += [("js", m.group(1)) for m in r.finditer(line)]
    return specs


def _norm_rel(root: Path, abspath: str) -> str | None:
    """Lexically normalize abspath to a posix path relative to root, or None if
    it escapes root (no filesystem/symlink resolution, for determinism)."""
    rel = os.path.relpath(os.path.normpath(abspath), start=os.path.normpath(str(root)))
    if rel.startswith(".."):
        return None
    return Path(rel).as_posix()


def _resolve_py(module: str, file_rel: str, root: Path, repo: set[str]) -> str | None:
    leading = len(module) - len(module.lstrip("."))
    parts = [p for p in module.lstrip(".").split(".") if p]
    if leading:
        base_dir = (root / file_rel).parent
        for _ in range(leading - 1):
            base_dir = base_dir.parent
        target = base_dir.joinpath(*parts) if parts else base_dir
        b = _norm_rel(root, str(target))
        if b is None:
            return None
        bases = [b]
    else:
        if not parts:
            return None
        bases = [Path(*parts).as_posix()]
    for b in bases:
        for cand in (f"{b}.py", f"{b}/__init__.py"):
            if cand in repo:
                return cand
    return None


def _resolve_js(spec: str, file_rel: str, root: Path, repo: set[str]) -> str | None:
    if spec.startswith("."):
        base = (root / file_rel).parent / spec
    elif spec.startswith("/"):
        base = root / spec.lstrip("/")
    else:
        return None  # bare/external specifier — not a repo file
    b = _norm_rel(root, str(base))
    if b is None:
        return None
    cands = [b] + [b + e for e in JS_EXTS] + [f"{b}/index{e}" for e in JS_EXTS]
    for c in cands:
        if c in repo:
            return c
    return None


def build_graph(files: list[Path], root: Path):
    """Return (repo_set, edges{src:set(dst)}, in_degree{rel:int}) for intra-repo
    imports among source files. External imports are dropped."""
    repo = {f.relative_to(root).as_posix() for f in files}
    edges: dict[str, set[str]] = {}
    indeg: dict[str, int] = {r: 0 for r in repo}
    for f in files:
        if f.suffix not in SOURCE_EXTS:
            continue
        rel = f.relative_to(root).as_posix()
        try:
            text = f.read_text(errors="ignore")
        except OSError:
            continue
        dsts: set[str] = set()
        for kind, spec in _file_imports(f, text):
            tgt = (_resolve_py if kind == "py" else _resolve_js)(spec, rel, root, repo)
            if tgt and tgt != rel:
                dsts.add(tgt)
        if dsts:
            edges[rel] = dsts
            for d in dsts:
                indeg[d] = indeg.get(d, 0) + 1
    return repo, edges, indeg


def build_smart_map(files: list[Path], root: Path, max_symbols: int) -> str:
    _repo, edges, indeg = build_graph(files, root)
    rels = [f.relative_to(root).as_posix() for f in files if f.suffix in SOURCE_EXTS]
    outdeg = {r: len(edges.get(r, ())) for r in rels}
    out = [
        "# Context map — " + (root.name or str(root)),
        "<!-- generated by scripts/compress-context.py (smart) -->",
        "",
        "Compact map for small-context models: entrypoints + ranked files + "
        "import graph + symbols. Deterministic; not a full repo dump.",
        "",
    ]
    entries: list[tuple[str, str]] = []
    for r in rels:
        stem = Path(r).stem
        if stem in ENTRY_STEMS:
            entries.append((r, f"name match: {stem}"))
        elif indeg.get(r, 0) == 0 and outdeg.get(r, 0) > 0:
            entries.append((r, f"imports {outdeg[r]}, imported-by 0"))
    entries.sort()
    out.append(f"## Entrypoints ({len(entries)})")
    out += [f"- `{r}`  ({why})" for r, why in entries] or ["(none detected)"]

    out += ["", f"## Ranked files by in-degree ({len(rels)})", "",
            "| in-degree | file |", "|---|---|"]
    for r in sorted(rels, key=lambda x: (-indeg.get(x, 0), x)):
        out.append(f"| {indeg.get(r, 0)} | `{r}` |")

    out += ["", "## Import graph (intra-repo edges)"]
    if edges:
        for src in sorted(edges):
            dsts = ", ".join(f"`{d}`" for d in sorted(edges[src]))
            out.append(f"- `{src}` → {dsts}")
    else:
        out.append("(no intra-repo imports resolved)")

    out += ["", "## Symbols"]
    any_syms = False
    for f in files:
        syms = extract_symbols(f, max_symbols, include_js=True)
        if not syms:
            continue
        any_syms = True
        out.append(f"### `{f.relative_to(root).as_posix()}`")
        out += [f"- {s}" for s in syms]
    if not any_syms:
        out.append("(no extractable symbols in supported languages)")
    return "\n".join(out).rstrip("\n") + "\n"


def over_budget(n_files: int, n_lines: int, n_bytes: int,
                max_files: int, max_lines: int, max_bytes: int) -> str | None:
    """Return an error message if the map exceeds any active budget, else None.
    A budget of 0 means 'no limit' for that dimension."""
    hits = []
    if max_files and n_files > max_files:
        hits.append(f"files {n_files} > --max-files {max_files}")
    if max_lines and n_lines > max_lines:
        hits.append(f"lines {n_lines} > --max-lines {max_lines}")
    if max_bytes and n_bytes > max_bytes:
        hits.append(f"bytes {n_bytes} > --max-bytes {max_bytes}")
    if not hits:
        return None
    return (
        "output too large for local-model context.\n"
        f"  {'; '.join(hits)}.\n"
        "  Scope the root more narrowly, add --exclude, raise the budgets "
        "(--max-files/--max-lines/--max-bytes), or pass --allow-large."
    )


def load_context_module():
    """Import scripts/wf-context.py as a module so we reuse its ONE resolver
    — no duplicate resolution logic (the tags_are_hints_not_truth boundary)."""
    spec = importlib.util.spec_from_file_location(
        "wf_context", SCRIPTS_DIR / "wf-context.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def resolve_from_tags(root: Path, tags_arg, story_arg, config_arg):
    """Resolve tags/story through the context registry to (files, names,
    obligations). Exits 1 on unknown tag, 2 on missing config/story."""
    ctx = load_context_module()
    config_path = Path(config_arg) if config_arg else root / "bmad.config.yaml"
    tags_map = ctx.load_tags(config_path)   # exits 2 on missing/malformed
    if story_arg:
        story = Path(story_arg)
        if not story.is_file():
            sys.stderr.write(f"compress-context: story not found: {story}\n")
            raise SystemExit(2)
        names, had = ctx.parse_story_tags(story.read_text())
        if not had:
            sys.stderr.write(f"compress-context: WARN {story.name}: no `Tags:` line\n")
    else:
        names = [t.strip() for t in tags_arg.split(",") if t.strip()]
    res = ctx.resolve_tags(tags_map, root, names)
    if res["unknown"]:
        sys.stderr.write("compress-context: unknown tag(s): "
                         f"{', '.join(res['unknown'])} (define them in the registry)\n")
        raise SystemExit(1)
    return [root / rel for rel in res["paths"]], names, res["obligations"]


def focus_header(names: list[str], obligations: list, n_files: int) -> str:
    lines = [f"# Focused context — tags: {', '.join(names) if names else '(none)'}",
             f"<!-- {n_files} tag-resolved file(s); via compress-context --tags -->",
             ""]
    if obligations:
        lines.append("## Risk obligations (satisfy before done)")
        lines += [f"- {tag}: {ob}" for tag, ob in obligations]
        lines.append("")
    lines += ["> Tags say where to START — not that nothing else matters. Verify "
              "imports, tests, deps, and security before editing.", "", ""]
    return "\n".join(lines)


def selftest() -> int:
    tmp = Path(tempfile.mkdtemp(prefix="compress-context-selftest-"))
    (tmp / "pkg").mkdir()
    (tmp / "pkg" / "mod.py").write_text(
        "import os\n\n\ndef alpha(x):\n    return x\n\n\nclass Beta:\n"
        "    def method(self):\n        pass\n")
    (tmp / "README.md").write_text("# Demo Project\n\nText.\n\n## Setup\n")
    (tmp / "__pycache__").mkdir()
    (tmp / "__pycache__" / "junk.pyc").write_text("x")
    # smart-mode fixture: a py + js import graph with entrypoints
    (tmp / "core.py").write_text("import os\n\n\nclass Core:\n    pass\n")
    (tmp / "app.py").write_text("from core import Core\n\n\ndef run():\n    return Core()\n")
    (tmp / "util.js").write_text("export function helper(x) {\n  return x;\n}\n")
    (tmp / "index.js").write_text("import { helper } from './util';\nhelper(1);\n")
    # a commented-out import must NOT create a false edge
    (tmp / "commented.js").write_text(
        "// import { helper } from './util'\nexport const noop = () => {};\n")
    files = collect_files(tmp, DEFAULT_EXCLUDES)
    out = build_map(files, tmp, 40)
    problems = []
    if "`pkg/mod.py`" not in out:
        problems.append("file inventory missing pkg/mod.py")
    if "def alpha(x)" not in out:
        problems.append("missing python function symbol")
    if "class Beta" not in out:
        problems.append("missing python class symbol")
    if "# Demo Project" not in out:
        problems.append("missing markdown heading symbol")
    if "junk.pyc" in out or "__pycache__" in out:
        problems.append("excluded directory leaked into the map")
    # budget: the small fixture is under generous budgets ...
    if over_budget(len(files), out.count("\n"), len(out), 400, 4000, 0):
        problems.append("small fixture wrongly flagged over budget")
    # ... but trips a deliberately tiny budget (fail-closed protection works)
    if not over_budget(len(files), out.count("\n"), len(out), 1, 4000, 0):
        problems.append("tiny --max-files budget was not enforced")
    if not over_budget(len(files), out.count("\n"), len(out), 0, 1, 0):
        problems.append("tiny --max-lines budget was not enforced")
    # default map must NOT contain smart-only sections (regression guard)
    if "## Entrypoints" in out or "## Import graph" in out:
        problems.append("default map leaked smart-only sections")
    # default map must NOT contain JS symbols (byte-identical guarantee: JS
    # extraction is smart-only). This is the assertion that catches the
    # shared-extract_symbols leak.
    if "export function helper" in out:
        problems.append("JS symbols leaked into the default map")
    # smart map: multi-lang symbols, import graph, ranking, entrypoints
    smart = build_smart_map(files, tmp, 40)
    if "export function helper(x)" not in smart:
        problems.append("smart map missing JS symbol")
    if "`app.py` → `core.py`" not in smart:
        problems.append("smart map missing py import edge app.py -> core.py")
    if "`index.js` → `util.js`" not in smart:
        problems.append("smart map missing js import edge index.js -> util.js")
    if "| 1 | `core.py` |" not in smart or "| 1 | `util.js` |" not in smart:
        problems.append("smart map in-degree ranking wrong for imported files")
    if "- `app.py`" not in smart or "- `index.js`" not in smart:
        problems.append("smart map missing expected entrypoints")
    if "`commented.js` →" in smart:
        problems.append("commented-out JS import created a false edge")
    # --tags (stage 5): restrict the map to tag-resolved files + risk obligations
    (tmp / "bmad.config.yaml").write_text(
        "context:\n  tags:\n"
        "    mod:\n      paths: [\"pkg/**\"]\n"
        "    SECURITY:\n      type: risk\n      paths: [\"pkg/**\"]\n"
        "      triggers: [\"require security review\"]\n")
    tf, tnames, tobl = resolve_from_tags(tmp, "mod,SECURITY", None, str(tmp / "bmad.config.yaml"))
    tfiles_rel = sorted(p.relative_to(tmp).as_posix() for p in tf)
    if tfiles_rel != ["pkg/mod.py"]:
        problems.append(f"--tags resolved wrong file set: {tfiles_rel}")
    if ("SECURITY", "require security review") not in tobl:
        problems.append("--tags did not carry the risk obligation")
    tmap = focus_header(tnames, tobl, len(tf)) + build_map(tf, tmp, 40)
    if "# Focused context" not in tmap or "require security review" not in tmap:
        problems.append("focus header missing tags/obligations")
    if "`pkg/mod.py`" not in tmap or "`core.py`" in tmap:
        problems.append("--tags map was not restricted to the resolved files")
    # an unknown tag fails closed (exit 1)
    try:
        resolve_from_tags(tmp, "ghost", None, str(tmp / "bmad.config.yaml"))
        problems.append("--tags unknown tag did not fail closed")
    except SystemExit as e:
        if e.code != 1:
            problems.append(f"--tags unknown tag exit {e.code}, expected 1")
    # cleanup
    for p in sorted(tmp.rglob("*"), reverse=True):
        p.rmdir() if p.is_dir() else p.unlink()
    tmp.rmdir()
    if problems:
        print("compress-context selftest: FAIL — " + "; ".join(problems))
        return 1
    print("compress-context selftest: PASS (files + py/md/js symbols, excludes + "
          "budgets; smart: import graph, in-degree ranking, entrypoints; "
          "--tags restrict + risk obligations + unknown-tag fail-closed)")
    return 0


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        prog="compress-context.py",
        description="Produce a compact context map (file inventory + symbols) of "
                    "a codebase for small-context models.",
    )
    parser.add_argument("root", nargs="?", default=".", help="directory to map (default: .)")
    parser.add_argument("--smart", action="store_true",
                        help="richer (still deterministic) map: JS/TS symbols, "
                             "import graph, in-degree ranking, entrypoints")
    parser.add_argument("--out", type=Path, default=None, help="output file (default: stdout)")
    parser.add_argument("--max-symbols", type=int, default=40,
                        help="max symbols per file (default: 40)")
    parser.add_argument("--exclude", default="",
                        help="comma-separated extra directory names to exclude")
    parser.add_argument("--max-files", type=int, default=400,
                        help="fail closed if the map exceeds this many files "
                             "(default: 400; 0 = no limit)")
    parser.add_argument("--max-lines", type=int, default=4000,
                        help="fail closed if the map exceeds this many lines "
                             "(default: 4000; 0 = no limit)")
    parser.add_argument("--max-bytes", type=int, default=0,
                        help="fail closed if the map exceeds this many bytes "
                             "(default: 0 = no limit)")
    parser.add_argument("--allow-large", action="store_true",
                        help="bypass the budget checks and emit anyway")
    parser.add_argument("--tags", default=None,
                        help="restrict the map to files resolved from these context "
                             "tags (comma-separated); see `wf context`")
    parser.add_argument("--story", default=None,
                        help="restrict the map to files resolved from a story's Tags: line")
    parser.add_argument("--config", default=None,
                        help="path to bmad.config.yaml for --tags/--story "
                             "(default: <root>/bmad.config.yaml)")
    parser.add_argument("--selftest", action="store_true",
                        help="run the bundled selftest and exit")
    args = parser.parse_args(argv)

    if args.selftest:
        return selftest()

    root = Path(args.root)
    if not root.is_dir():
        sys.stderr.write(f"compress-context: not a directory: {root}\n")
        return 2
    excludes = set(DEFAULT_EXCLUDES)
    excludes.update(n.strip() for n in args.exclude.split(",") if n.strip())
    focus = ""
    if args.tags or args.story:
        if args.tags and args.story:
            sys.stderr.write("compress-context: use one of --tags or --story\n")
            return 2
        files, names, obligations = resolve_from_tags(
            root, args.tags, args.story, args.config)
        focus = focus_header(names, obligations, len(files))
    else:
        files = collect_files(root, excludes)
    content = focus + (build_smart_map if args.smart else build_map)(
        files, root, args.max_symbols)
    if not args.allow_large:
        err = over_budget(len(files), content.count("\n"), len(content),
                          args.max_files, args.max_lines, args.max_bytes)
        if err:
            sys.stderr.write(f"compress-context: {err}\n")
            return 2
    if args.out:
        args.out.write_text(content)
        print(f"wrote {args.out}")
    else:
        sys.stdout.write(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
