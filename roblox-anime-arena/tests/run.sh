#!/usr/bin/env bash
#
# Runs the pure-logic test suite outside Roblox.
#
#   ./tests/run.sh                 # uses `luau` from PATH
#   LUAU=/path/to/luau ./tests/run.sh
#
# The Luau CLI sandbox has no `io` library, so module sources cannot be read at
# runtime. This script bundles them into a generated Luau table first, which the
# harness then loads with loadstring.

set -euo pipefail

cd "$(dirname "$0")/.."

LUAU="${LUAU:-luau}"
if ! command -v "$LUAU" >/dev/null 2>&1; then
	echo "error: luau not found. Install it, or set LUAU=/path/to/luau." >&2
	exit 1
fi

OUT="tests/.sources.luau"
MODULES=(
	"Config/Rarities"
	"Config/Traits"
	"Config/Mutations"
	"Config/Units"
	"Config/GameConfig"
	"Config/Upgrades"
	"Config/Waves"
	"Config/ShopConfig"
	"Config/Items"
	"Config/Codes"
	"Config/Monetization"
	"Util/StatMath"
	"Util/WeightedPick"
	"Util/Format"
)

{
	echo "-- GENERATED by tests/run.sh — do not edit."
	echo "return {"
	for module in "${MODULES[@]}"; do
		path="src/shared/${module}.luau"
		if [[ ! -f "$path" ]]; then
			echo "error: missing $path" >&2
			exit 1
		fi
		# A long-bracket level of 5 equals-signs will not collide with any
		# bracket sequence in normal Luau source.
		printf '\t["%s"] = [=====[\n' "$module"
		cat "$path"
		printf ']=====],\n'
	done
	echo "}"
} >"$OUT"

"$LUAU" tests/run.luau
status=$?

rm -f "$OUT"
exit $status
